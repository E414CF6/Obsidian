export function formatMcIdentifier(id: string): string {
    if (ITEM_BLOCK_KO[id]) {
        return `${ITEM_BLOCK_KO[id]} (${id})`;
    }
    return id
        .split("_")
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join(" ");
}

export function formatBiomeName(id: string): string {
    return BIOME_KO[id] || id.replace(/_/g, " ");
}

export function formatAdvancementName(key: string): string {
    if (ADVANCEMENT_KO[key]) return ADVANCEMENT_KO[key];
    const [, slug] = key.split("/");
    if (!slug) return key;
    return slug
        .split("_")
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join(" ");
}
